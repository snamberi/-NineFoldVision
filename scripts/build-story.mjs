// Turns every book in content/books/*.md into data the site reads:
//   site/data/books.js          the shelf (titles, chapter names, word counts), loaded by every story page
//   site/data/book-<slug>.js    one book's full text, loaded only by the reader
//   site/read/ch-<n>.html       a share page per chapter of the first book: link previews (Discord, WhatsApp, X)
//                               show the chapter's title and card image, then the page opens it in the reader
// Run: node scripts/build-story.mjs   (then python3 scripts/build-share-cards.py for the card images)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const booksDir = join(root, 'content/books')
const dataDir = join(root, 'site/data')

const words = s => s.split(/\s+/).filter(Boolean).length

function parse(file) {
  const raw = readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
  const fm = raw.match(/^---\n([\s\S]*?)\n---\n/)
  const meta = {}
  if (fm) for (const line of fm[1].split('\n')) {
    const i = line.indexOf(':')
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim()
  }
  const body = fm ? raw.slice(fm[0].length) : raw
  const chapters = []
  for (const block of body.split(/\n(?=## )/)) {
    const m = block.match(/^## (?:Chapter \d+:\s*)?(.+)\n([\s\S]*)$/)
    if (!m) continue
    const paragraphs = m[2].split(/\n\s*\n/).map(p => p.replace(/\s*\n\s*/g, ' ').trim()).filter(Boolean)
    chapters.push({ n: chapters.length + 1, title: m[1].trim(), paragraphs })
  }
  const slug = basename(file, '.md')
  return { slug, title: meta.title || slug, series: meta.series || '', book: Number(meta.book) || 1, tagline: meta.tagline || '', chapters }
}

const books = readdirSync(booksDir).filter(f => f.endsWith('.md')).sort().map(f => parse(join(booksDir, f)))
  .sort((a, b) => a.book - b.book)

const header = '// Generated by scripts/build-story.mjs from content/books. Edit the Markdown, not this file.\n'
const shelf = books.map(b => ({
  slug: b.slug, title: b.title, series: b.series, book: b.book, tagline: b.tagline,
  words: b.chapters.reduce((t, c) => t + c.paragraphs.reduce((s, p) => s + words(p), 0), 0),
  chapters: b.chapters.map(c => ({ n: c.n, title: c.title, words: c.paragraphs.reduce((s, p) => s + words(p), 0) })),
}))
writeFileSync(join(dataDir, 'books.js'), `${header}window.NFV_BOOKS = ${JSON.stringify(shelf, null, 1)};\n`)
for (const b of books) {
  const text = b.chapters.map(c => ({ n: c.n, title: c.title, paragraphs: c.paragraphs }))
  writeFileSync(join(dataDir, `book-${b.slug}.js`), `${header}window.NFV_BOOK_TEXT = window.NFV_BOOK_TEXT || {};\nwindow.NFV_BOOK_TEXT[${JSON.stringify(b.slug)}] = ${JSON.stringify(text)};\n`)
  console.log(`${b.title}: ${b.chapters.length} chapters, ${shelf.find(s => s.slug === b.slug).words} words`)
}

// Share pages. Link previews never run JavaScript or read the #ch-N part of a link, so every chapter needs
// its own small page with its own tags.
const site = 'https://ninefoldvision.online'
const attr = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')
const first = books[0]
mkdirSync(join(root, 'site/read'), { recursive: true })
for (const c of first.chapters) {
  const title = `Chapter ${c.n}: ${c.title} · ${first.title}`
  const opening = c.paragraphs[0] || ''
  const desc = opening.length > 180 ? `${opening.slice(0, 177).replace(/\s+\S*$/, '')}…` : opening
  const reader = `../story.html#ch-${c.n}`
  writeFileSync(join(root, `site/read/ch-${c.n}.html`), `<!doctype html>
<!-- Generated by scripts/build-story.mjs. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${attr(title)}</title>
  <meta name="description" content="${attr(desc)}">
  <link rel="canonical" href="${site}/read/ch-${c.n}.html">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="NineFoldVision">
  <meta property="og:title" content="${attr(title)}">
  <meta property="og:description" content="${attr(desc)}">
  <meta property="og:url" content="${site}/read/ch-${c.n}.html">
  <meta property="og:image" content="${site}/assets/img/share/ch-${c.n}.png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="${attr(`${first.title}, chapter ${c.n}: ${c.title}`)}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="theme-color" content="#f6892f">
  <link rel="icon" type="image/png" href="../assets/img/logo-favicon.png">
  <meta http-equiv="refresh" content="0; url=${reader}">
  <script>location.replace('${reader}')</script>
</head>
<body style="background:#0f1016;color:#eeeef3;font-family:system-ui,sans-serif;padding:40px">
  <p><a style="color:#f6892f" href="${reader}">Read chapter ${c.n}: ${attr(c.title)}</a></p>
</body>
</html>
`)
}
console.log(`Share pages: site/read/ch-1.html to ch-${first.chapters.length}.html`)
