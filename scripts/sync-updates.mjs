// Copies each game's in-game release notes into site/data/game-updates.js, so the studio site's Updates
// pages stay in step with the games. Where each game keeps its notes is set in scripts/update-sources.json
// (a path to the game's checkout, relative to this repo, and the file with its `RELEASES` list).
//   node scripts/sync-updates.mjs                 every game whose checkout is found
//   node scripts/sync-updates.mjs dragonvision    one game
// A game whose checkout isn't on this machine keeps the updates it already had.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sources = JSON.parse(readFileSync(join(root, 'scripts/update-sources.json'), 'utf8'))
const outFile = join(root, 'site/data/game-updates.js')

const current = {}
if (existsSync(outFile)) {
  const window = {}
  new Function('window', readFileSync(outFile, 'utf8'))(window)
  Object.assign(current, window.NFV_GAME_UPDATES)
}

/** The `RELEASES` array literal from a TypeScript source file, evaluated as plain data. */
function readReleases(source) {
  const start = source.indexOf('= [', source.indexOf('export const RELEASES')) + 2
  let depth = 0, end = start, quote = null
  for (let i = start; i < source.length; i++) {
    const ch = source[i]
    if (quote) { if (ch === '\\') i++; else if (ch === quote) quote = null; continue }
    if (ch === '"' || ch === "'" || ch === '`') quote = ch
    else if (ch === '[') depth++
    else if (ch === ']' && --depth === 0) { end = i + 1; break }
  }
  return new Function(`return ${source.slice(start, end)}`)()
}

// The headline of each item: its bold lead-in, or its first words (the same rule the games use).
const headOf = text => {
  const bold = text.match(/^\*\*([^*]+?)[:.]?\*\*/)
  if (bold) return bold[1].trim().replace(/[:.]$/, '')
  const first = text.replace(/\*\*/g, '').split(/[.:;]\s/)[0]
  return first.length > 60 ? `${first.slice(0, 57).trimEnd()}…` : first
}

const only = process.argv[2]
for (const [slug, src] of Object.entries(sources)) {
  if (only && slug !== only) continue
  const file = resolve(root, src.repo, src.file)
  if (!existsSync(file)) { console.log(`${slug}: ${file} not found, keeping ${current[slug]?.length ?? 0} updates`); continue }
  const releases = readReleases(readFileSync(file, 'utf8'))
  // Numbered by the game's own id when it is a number (Update 13), otherwise by position (oldest is 1).
  current[slug] = releases.map((r, i) => ({
    number: typeof r.id === 'number' ? r.id : releases.length - i,
    title: r.title,
    items: r.items.map(text => ({ head: headOf(text), text })),
  }))
  console.log(`${slug}: ${current[slug].length} updates`)
}

writeFileSync(outFile, '// Generated by scripts/sync-updates.mjs from each game\'s release notes. Do not edit by hand.\n'
  + `window.NFV_GAME_UPDATES = ${JSON.stringify(current, null, 1)};\n`)
