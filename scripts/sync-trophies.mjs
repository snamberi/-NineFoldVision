// Copies each game's achievement names into site/data/trophies.js, so profiles can show a player's trophies
// by name. Reads the games from checkouts next to this repo (../CourtVision, ../dragonvision); for Court Vision
// it prefers the published main branch (`git show origin/main:…`) and falls back to the working tree.
//   node scripts/sync-trophies.mjs
// A game whose checkout isn't on this machine keeps the trophies it already had.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'site/data/trophies.js')

const current = {}
if (existsSync(outFile)) {
  const window = {}
  new Function('window', readFileSync(outFile, 'utf8'))(window)
  Object.assign(current, window.NFV_TROPHIES)
}

/** A file from a game checkout: origin/main first (what players have), then the working tree. */
function read(repo, file) {
  const dir = resolve(root, repo)
  if (!existsSync(dir)) return null
  try { return execFileSync('git', ['-C', dir, 'show', `origin/main:${file}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }) } catch { /* no remote main */ }
  const path = join(dir, file)
  return existsSync(path) ? readFileSync(path, 'utf8') : null
}

const unquote = s => s.slice(1, -1).replace(/\\(['"`\\])/g, '$1')
const STR = `('(?:[^'\\\\]|\\\\.)*'|"(?:[^"\\\\]|\\\\.)*")`

/** Every `{ id: '…', … name: '…', … <textKey>: '…' }` entry in a source file. */
function entries(source, textKey) {
  const out = []
  const re = new RegExp(`\\{\\s*id:\\s*${STR}([^\\n]*?)name:\\s*${STR}[^\\n]*?${textKey}:\\s*${STR}`, 'g')
  for (const m of source.matchAll(re)) {
    const mode = m[2].match(new RegExp(`mode:\\s*${STR}`))
    out.push({ id: unquote(m[1]), name: unquote(m[3]), text: unquote(m[4]), mode: mode ? unquote(mode[1]) : undefined })
  }
  return out
}

const result = { ...current }

// Court Vision: front-office achievements keep their ids; mode achievements are stored as "mode-<id>".
{
  const fo = read('../CourtVision', 'src/simulation/frontOffice.ts')
  const modes = read('../CourtVision', 'src/profile/modeAchievements.ts')
  if (fo && modes) {
    const labels = {}
    const labelBlock = modes.match(/MODE_LABELS[^{]*\{([\s\S]*?)\};/)
    if (labelBlock) for (const m of labelBlock[1].matchAll(new RegExp(`([a-z]+):\\s*${STR}`, 'g'))) labels[m[1]] = unquote(m[2])
    const list = {}
    for (const a of entries(fo, 'description')) list[a.id] = { name: a.name, text: a.text, group: 'Franchise' }
    for (const a of entries(modes, 'description')) list[`mode-${a.id}`] = { name: a.name, text: a.text, group: labels[a.mode] || 'Modes' }
    result.courtvision = list
    console.log(`courtvision: ${Object.keys(list).length} trophies`)
  } else console.log(`courtvision: checkout not found, keeping ${Object.keys(current.courtvision || {}).length}`)
}

// Dragon Vision: src/game/achievements.ts (`text` is the description).
{
  const src = read('../dragonvision', 'src/game/achievements.ts')
  if (src) {
    const list = {}
    for (const a of entries(src, 'text')) list[a.id] = { name: a.name, text: a.text, group: 'Achievements' }
    result.dragonvision = list
    console.log(`dragonvision: ${Object.keys(list).length} trophies`)
  } else console.log(`dragonvision: checkout not found, keeping ${Object.keys(current.dragonvision || {}).length}`)
}

writeFileSync(outFile, `// Generated by scripts/sync-trophies.mjs. Do not edit by hand.\nwindow.NFV_TROPHIES = ${JSON.stringify(result, null, 1)};\n`)
